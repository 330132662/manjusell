function gfMul(a, b) {
  let r = 0
  for (let i = 0; i < 8; i++) {
    if (b & 1) r ^= a
    const hi = a & 0x80
    a = (a << 1) & 0xff
    if (hi) a ^= 0x1b
    b >>= 1
  }
  return r
}


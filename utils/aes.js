/* ---------- 密钥扩展 ---------- */
const RCON = [0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36]

function expandKey(keyBytes) {
  // AES-128: 16 字节 -> 176 字节(44 个字)
  const w = new Array(44)
  for (let i = 0; i < 16; i++) w[i] = keyBytes[i]
  let temp
  for (let i = 4; i < 44; i++) {
    temp = w.slice((i - 1) * 4, i * 4)
    if (i % 4 === 0) {
      // RotWord + SubWord + Rcon（Rcon 异或到轮键字首字节）
      temp = [SB[temp[1]] ^ RCON[i / 4], SB[temp[2]], SB[temp[3]], SB[temp[0]]]
    }
    for (let j = 0; j < 4; j++) {
      w[i * 4 + j] = w[(i - 4) * 4 + j] ^ temp[j]
    }
  }
  return w
}

/* ---------- 单个 16 字节块加密 ---------- */
function encryptBlock(block, w) {
  const state = block.slice()
  let round = 0

  function addRoundKey(r) {
    for (let i = 0; i < 16; i++) state[i] ^= w[r * 16 + i]
  }
  function subBytes() {
    for (let i = 0; i < 16; i++) state[i] = SB[state[i]]
  }
  function shiftRows() {
    const t = state.slice()
    // row1 左移1, row2 左移2, row3 左移3
    state[1] = t[5]; state[5] = t[9]; state[9] = t[13]; state[13] = t[1]
    state[2] = t[10]; state[6] = t[14]; state[10] = t[2]; state[14] = t[6]
    state[3] = t[15]; state[7] = t[3]; state[11] = t[7]; state[15] = t[11]
  }
  function mixColumns() {
    for (let c = 0; c < 4; c++) {
      const i0 = c * 4, i1 = c * 4 + 1, i2 = c * 4 + 2, i3 = c * 4 + 3
      const a0 = state[i0], a1 = state[i1], a2 = state[i2], a3 = state[i3]
      state[i0] = gfMul(2, a0) ^ gfMul(3, a1) ^ a2 ^ a3
      state[i1] = a0 ^ gfMul(2, a1) ^ gfMul(3, a2) ^ a3
      state[i2] = a0 ^ a1 ^ gfMul(2, a2) ^ gfMul(3, a3)
      state[i3] = gfMul(3, a0) ^ a1 ^ a2 ^ gfMul(2, a3)
    }
  }

  addRoundKey(round)
  for (round = 1; round < 10; round++) {
    subBytes()
    shiftRows()
    mixColumns()
    addRoundKey(round)
  }
  subBytes()
  shiftRows()
  addRoundKey(10)
  return state
}

